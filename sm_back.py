def interactive_mode():
    sm = DeviceStateMachine()

    print("=" * 58)
    print("  기기 상태 머신 시뮬레이터")
    print("=" * 58)

    EVENTS = list(Event)
    EXCEPTIONS = list(ExceptionType)

    while True:
        print()
        print(sm.status())
        print()
        print("  [이벤트]")
        for i, e in enumerate(EVENTS, 1):
            print(f"    {i}. {e.value}")
        print()
        print("  [예외]")
        for i, exc in enumerate(EXCEPTIONS, 1):
            print(f"    {len(EVENTS)+i}. EXC: {exc.value}")
        print()
        print("  [기타]  q=종료  r=리셋  s=상태 재출력")
        print("-" * 58)

        choice = input("  선택 > ").strip().lower()

        if choice == 'q':
            print("\n  종료합니다.")
            break
        elif choice == 'r':
            sm = DeviceStateMachine()
            print("\n  머신을 초기화했습니다.")
        elif choice == 's':
            continue
        elif choice.isdigit():
            idx = int(choice)
            if 1 <= idx <= len(EVENTS):
                evt = EVENTS[idx - 1]
                print(f"\n  ▶ 이벤트 발동: {evt.value}")
                sm.trigger(evt)
            elif len(EVENTS) < idx <= len(EVENTS) + len(EXCEPTIONS):
                exc = EXCEPTIONS[idx - len(EVENTS) - 1]
                print(f"\n  ⚡ 예외 발동: {exc.value}")
                sm.handle_exception(exc)
            else:
                print("  잘못된 번호입니다.")
        else:
            print("  알 수 없는 입력입니다.")


