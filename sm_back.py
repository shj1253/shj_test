def run_scenario():
    """정상 흐름 + 예외 흐름 시나리오 자동 실행"""
    print("=" * 58)
    print("  시나리오 테스트")
    print("=" * 58)

    sm = DeviceStateMachine()

    steps = [
        ("정상 전이: T1 → T2",          lambda: sm.trigger(Event.POWER_BUTTON)),
        ("예외: T2 Soft Error1 (유지)",   lambda: sm.handle_exception(ExceptionType.SOFT_ERROR_1)),
        ("정상 전이: T2 → T3",           lambda: sm.trigger(Event.BTN_123)),
        ("예외: T3 Soft Error1 (유지)",   lambda: sm.handle_exception(ExceptionType.SOFT_ERROR_1)),
        ("정상 전이: T3 → FACTORY",      lambda: sm.trigger(Event.FACTORY_BUTTON)),
        ("예외: FACTORY Soft Error*",     lambda: sm.handle_exception(ExceptionType.SOFT_ERROR_STAR)),
        ("정상 전이: T3 → FACTORY",      lambda: sm.trigger(Event.FACTORY_BUTTON)),
        ("정상 전이: FACTORY → T3",      lambda: sm.trigger(Event.BTN_04)),
        # T3_RETRY → T3_NO_RETRY 로 강제 이동 후 T4 진행
        ("강제 상태 변경: T3_NO_RETRY",   lambda: setattr(sm, 'state', State.T3_NO_RETRY) or None),
        ("정상 전이: T3 → T4",           lambda: sm.trigger(Event.FACTORY_BUTTON)),
        ("예외: T4 Hard Error",           lambda: sm.handle_exception(ExceptionType.HARD_ERROR)),
        ("관리자 리셋: ERROR → T1",       lambda: sm.trigger(Event.ADMIN_RESET)),
    ]

    for desc, fn in steps:
        print(f"\n>>> {desc}")
        fn()

    print()
    print("=" * 58)
    print("  최종 상태:")
    print(sm.status())
    print("=" * 58)


